namespace Robot.Forms
{

    /// <summary>
    /// 窗口阴影效果类型。
    /// </summary>
    public enum ShadowEffect
    {
        /// <summary>
        /// 无阴影。
        /// </summary>
        None = 0,

        /// <summary>
        /// 发光效果。
        /// </summary>
        Glow,

        /// <summary>
        /// 小阴影。
        /// </summary>
        Small,

        /// <summary>
        /// 普通阴影。
        /// </summary>
        Normal,

        /// <summary>
        /// 大阴影。
        /// </summary>
        Big,

        /// <summary>
        /// 超大阴影。
        /// </summary>
        Huge,

        /// <summary>
        /// 投影 (Drop Shadow)。
        /// </summary>
        DropShadow,
    }
}